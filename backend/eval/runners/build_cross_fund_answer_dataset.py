def named_fund_calls(query: str, codes: list[str]) -> list[dict]:
    calls = []
    for code in codes:
        if not re.search(rf"(?<!\d){re.escape(code)}(?!\d)", query):
            calls.append({"name": "rag_identify_funds"})
        calls.append({"name": "rag_search", "args": {"filter_fund_code": code}})
    return calls


NUMBER_RE = re.compile(r"(?<![\d.])-?\d[\d,]*(?:\.\d+)?%?")
DATE_RE = re.compile(r"\d{4}(?:年\d{1,2}月\d{1,2}日|-\d{1,2}-\d{1,2})")
SKIPPABLE_DETAIL_LABELS = {
    "",
    "个人",
    "机构",
    "成立",
    "上市",
    "天",
    "份",
    "每",
    "每份",
    "年度利润分配",
    "年度未进行利润分配",
    "自基金合同生效以来未进行利润分配",
    "未进行利润分配",
    "无",
}


def split_compound_key_fact(fact: str) -> list[str]:
    """把带基金前缀的复合事实拆分为原子实体和值。"""
    if re.search(r"[:：]", fact):
        entity, detail = re.split(r"[:：]", fact, maxsplit=1)
        parts = [entity.strip()]
        segments = re.split(r"[，、/；;]", detail)
    else:
        parts = []
        segments = re.split(r"[，、/；;]", fact)

    for segment in segments:
        segment = segment.strip()
        if not segment:
            continue

        values = []
        consumed_spans = []
        for match in DATE_RE.finditer(segment):
            values.append(match.group())
            consumed_spans.append(match.span())
        for match in NUMBER_RE.finditer(segment):
            if any(start <= match.start() and match.end() <= end for start, end in consumed_spans):
                continue
            values.append(match.group())
            consumed_spans.append(match.span())

        residual = DATE_RE.sub("", segment)
        residual = NUMBER_RE.sub("", residual)
        residual = re.sub(r"[元份]$", "", residual).strip()
        if residual and residual not in SKIPPABLE_DETAIL_LABELS:
            parts.append(residual)
        parts.extend(values)

    return [part for part in parts if part]


def normalize_key_facts(key_facts: list[str]) -> list[str]:
    """把复合事实拆分为原子实体和值。"""
    normalized = []
    for fact in key_facts:
        for value in split_compound_key_fact(fact):
            normalized.append(value)
    return normalized

