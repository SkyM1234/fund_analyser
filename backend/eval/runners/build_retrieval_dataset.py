def get_first_report_codes(markdown_root):
    reports = sorted(
        markdown_root.rglob("*_analyzed.md"),
        key=lambda path: str(path.resolve()).lower(),
    )[: len(EXPECTED_FUND_CODES)]
    if len(reports) != len(EXPECTED_FUND_CODES):
        raise ValueError(
            "Expected at least %d *_analyzed.md files, found %d"
            % (len(EXPECTED_FUND_CODES), len(reports))
        )

    codes = []
    for report in reports:
        match = re.match(r"(\d{6})_", report.name)
        if not match:
            raise ValueError("Cannot parse fund code from %s" % report)
        codes.append(match.group(1))

    if codes != EXPECTED_FUND_CODES:
        raise ValueError(
            "Report codes changed. Expected %s, got %s"
            % (EXPECTED_FUND_CODES, codes)
        )
    return reports


def header_path(chunk):
    return " > ".join(
        str(chunk.get("header_%d" % level, "")).strip()
        for level in range(1, 7)
        if str(chunk.get("header_%d" % level, "")).strip()
    )


def fetch_chunks(client, collection, fund_code, indexes):
    index_list = ", ".join(str(index) for index in sorted(indexes))
    rows = client.query(
        collection_name=collection,
        filter='fund_code == "%s" and chunk_index in [%s]'
        % (fund_code, index_list),
        output_fields=[
            "id", "fund_code", "content", "chunk_index", "header_1",
            "header_2", "header_3", "header_4", "header_5", "header_6",
            "file_path",
        ],
        limit=1000,
    )
    chunks = {int(row["chunk_index"]): row for row in rows}
    missing = sorted(set(indexes) - set(chunks))
    if missing:
        raise ValueError(
            "Milvus is missing chunks for fund %s: %s" % (fund_code, missing)
        )
    return chunks


def build_examples(client, collection, fund_codes, start_sequence):
    counts = {code: len(specs) for code, specs in QUESTION_SPECS.items()}
    if list(QUESTION_SPECS) != EXPECTED_FUND_CODES:
        raise ValueError("Question specs must follow report order")
    if any(count != 10 for count in counts.values()):
        raise ValueError("Each fund must have exactly 10 questions: %s" % counts)

    examples = []
    sequence = start_sequence
    for fund_code in fund_codes:
        specs = QUESTION_SPECS[fund_code]
        needed_indexes = {index for spec in specs for index in spec["chunks"]}
        chunks = fetch_chunks(client, collection, fund_code, needed_indexes)
        for spec in specs:
            selected = [chunks[index] for index in spec["chunks"]]
            combined_content = "\n".join(chunk["content"] for chunk in selected)
            missing_keywords = [
                keyword for keyword in spec["keywords"]
                if keyword not in combined_content
            ]
            if missing_keywords:
                raise ValueError(
                    "%s is missing keywords %s in chunks %s"
                    % (fund_code, missing_keywords, spec["chunks"])
                )

            chunk_notes = []
            for chunk in selected:
                file_path = str(chunk.get("file_path", ""))
                if not file_path.endswith("_analyzed.md") or (
                    "%s_" % fund_code not in Path(file_path).name
                ):
                    raise ValueError(
                        "Chunk %s has unexpected file path %s"
                        % (chunk["id"], file_path)
                    )
                path = header_path(chunk)
                leaf = path.split(" > ")[-1] if path else "无章节标题"
                chunk_notes.append("chunk=%s %s" % (chunk["chunk_index"], leaf))

            examples.append({
                "id": "retrieval-%03d" % sequence,
                "query": spec["query"],
                "filter_fund_code": fund_code,
                "top_k": 10,
                "expected_fund_codes": [fund_code],
                "relevant_chunk_ids": [chunk["id"] for chunk in selected],
                "relevant_keywords": spec["keywords"],
                "category": "single_fund",
                "note": "%s %s；%s" % (
                    fund_code, spec["topic"], "；".join(chunk_notes)
                ),
            })
            sequence += 1
    return examples


def validate_examples(examples):
    expected_total = len(EXPECTED_FUND_CODES) * 10
    if len(examples) != expected_total:
        raise ValueError("Expected %d examples, got %d" % (expected_total, len(examples)))

    expected_ids = ["retrieval-%03d" % index for index in range(1, expected_total + 1)]
    if [example["id"] for example in examples] != expected_ids:
        raise ValueError("Example IDs are not continuous")

    counts = Counter(example["filter_fund_code"] for example in examples)
    if dict(counts) != {code: 10 for code in EXPECTED_FUND_CODES}:
        raise ValueError("Unexpected per-fund counts: %s" % dict(counts))

    queries = [example["query"] for example in examples]
    if len(set(queries)) != len(queries):
        raise ValueError("Duplicate queries found")
    for example in examples:
        if not example["relevant_chunk_ids"]:
            raise ValueError("%s has no relevant chunk IDs" % example["id"])
        if len(set(example["relevant_chunk_ids"])) != len(example["relevant_chunk_ids"]):
            raise ValueError("%s has duplicate chunk IDs" % example["id"])


def write_jsonl(path, examples):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        for example in examples:
            handle.write(json.dumps(example, ensure_ascii=False) + "\n")


def load_jsonl(path):
    if not path.exists():
        return []
    with path.open(encoding="utf-8") as handle:
        return [json.loads(line) for line in handle if line.strip()]


def main():
    args = parse_args()
    existing = load_jsonl(args.output)
    historical_count = len(HISTORICAL_FUND_CODES) * 10
    if len(existing) not in (historical_count, historical_count + len(CURRENT_BATCH_FUND_CODES) * 10):
        raise ValueError(
            "Expected existing dataset to contain %d or %d examples, got %d"
            % (historical_count, historical_count + len(CURRENT_BATCH_FUND_CODES) * 10, len(existing))
        )

    if not CURRENT_BATCH_FUND_CODES:
        validate_examples(existing)
        print("Validated %d examples for %d funds at %s" % (
            len(existing), len(EXPECTED_FUND_CODES), args.output
        ))
        return

    get_first_report_codes(args.markdown_root)
    if len(existing) == historical_count:
        client = MilvusClient(uri=args.milvus_uri)
        examples = existing + build_examples(
            client, args.collection, CURRENT_BATCH_FUND_CODES, historical_count + 1
        )
    else:
        examples = existing

    validate_examples(examples)
    write_jsonl(args.output, examples)
    print("Wrote %d examples for %d funds to %s" % (
        len(examples), len(EXPECTED_FUND_CODES), args.output
    ))


if __name__ == "__main__":
    main()
