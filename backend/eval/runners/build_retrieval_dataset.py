def parse_args():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--milvus-uri",
        default=os.getenv("MILVUS_URI", "http://localhost:19595"),
        help="Milvus URI (default: %(default)s)",
    )
    parser.add_argument(
        "--collection",
        default=os.getenv("MILVUS_COLLECTION", "fund_reports_mineru"),
        help="Milvus collection (default: %(default)s)",
    )
    parser.add_argument(
        "--markdown-root",
        type=Path,
        default=DEFAULT_MARKDOWN_ROOT,
        help="Root containing *_analyzed.md files",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT,
        help="JSONL output path",
    )
    return parser.parse_args()


def get_first_report_codes(markdown_root):
    reports = sorted(
        markdown_root.rglob("*_analyzed.md"),
        key=lambda path: str(path.resolve()).lower(),
    )[:30]
    if len(reports) != 30:
        raise ValueError(
            "Expected at least 30 *_analyzed.md files, found %d" % len(reports)
        )

    codes = []
    for report in reports:
        match = re.match(r"(\d{6})_", report.name)
        if not match:
            raise ValueError("Cannot parse fund code from %s" % report)
        codes.append(match.group(1))

    if codes != EXPECTED_FUND_CODES:
        raise ValueError(
            "First 30 report codes changed. Expected %s, got %s"
            % (EXPECTED_FUND_CODES, codes)
        )
    return reports


def header_path(chunk):
    return " > ".join(
        str(chunk.get("header_%d" % level, "")).strip()
        for level in range(1, 7)
        if str(chunk.get("header_%d" % level, "")).strip()
    )


def fetch_chunks(client, collection, fund_code, indexes):
    index_list = ", ".join(str(index) for index in sorted(indexes))
    rows = client.query(
        collection_name=collection,
        filter='fund_code == "%s" and chunk_index in [%s]'
        % (fund_code, index_list),
        output_fields=[
            "id",
            "fund_code",
            "fund_name",
            "content",
            "chunk_index",
            "header_1",
            "header_2",
            "header_3",
            "header_4",
            "header_5",
            "header_6",
            "file_path",
        ],
        limit=1000,
    )
    chunks = {int(row["chunk_index"]): row for row in rows}
    missing = sorted(set(indexes) - set(chunks))
    if missing:
        raise ValueError(
            "Milvus is missing chunks for fund %s: %s" % (fund_code, missing)
        )
    for chunk in chunks.values():
        if str(chunk.get("fund_code")) != fund_code:
            raise ValueError(
                "Chunk %s belongs to fund %s, expected %s"
                % (chunk.get("id"), chunk.get("fund_code"), fund_code)
            )
    return chunks


def build_examples(client, collection):
    counts = {code: len(specs) for code, specs in QUESTION_SPECS.items()}
    if list(QUESTION_SPECS) != EXPECTED_FUND_CODES:
        raise ValueError("Question specs must follow the first 30 report order")
    if any(count != 10 for count in counts.values()):
        raise ValueError("Each fund must have exactly 10 questions: %s" % counts)

    examples = []
    sequence = 1
    for fund_code in EXPECTED_FUND_CODES:
        specs = QUESTION_SPECS[fund_code]
        needed_indexes = {
            index for spec in specs for index in spec["chunks"]
        }
        chunks = fetch_chunks(client, collection, fund_code, needed_indexes)

        for spec in specs:
            selected = [chunks[index] for index in spec["chunks"]]
            combined_content = "\n".join(chunk["content"] for chunk in selected)
            missing_keywords = [
                keyword
                for keyword in spec["keywords"]
                if keyword not in combined_content
            ]
            if missing_keywords:
                raise ValueError(
                    "%s is missing keywords %s in chunks %s"
                    % (fund_code, missing_keywords, spec["chunks"])
                )

            chunk_notes = []
            for chunk in selected:
                path = header_path(chunk)
                leaf = path.split(" > ")[-1] if path else "无章节标题"
                chunk_notes.append(
                    "chunk=%s %s" % (chunk["chunk_index"], leaf)
                )

            examples.append(
                {
                    "id": "retrieval-%03d" % sequence,
                    "query": spec["query"],
                    "filter_fund_code": fund_code,
                    "top_k": 10,
                    "expected_fund_codes": [fund_code],
                    "relevant_chunk_ids": [chunk["id"] for chunk in selected],
                    "relevant_keywords": spec["keywords"],
                    "category": "single_fund",
                    "note": "%s %s；%s"
                    % (fund_code, spec["topic"], "；".join(chunk_notes)),
                }
            )
            sequence += 1

    return examples


def validate_examples(examples):
    if len(examples) != 300:
        raise ValueError("Expected 300 examples, got %d" % len(examples))

    ids = [example["id"] for example in examples]
    expected_ids = ["retrieval-%03d" % index for index in range(1, 301)]
    if ids != expected_ids:
        raise ValueError("Example IDs are not continuous from 001 to 300")

    counts = Counter(example["filter_fund_code"] for example in examples)
    expected_counts = {code: 10 for code in EXPECTED_FUND_CODES}
    if dict(counts) != expected_counts:
        raise ValueError("Unexpected per-fund counts: %s" % dict(counts))

    current_batch = [
        example
        for example in examples
        if example["filter_fund_code"] in CURRENT_BATCH_FUND_CODES
    ]
    if len(current_batch) != 100:
        raise ValueError(
            "Expected 100 current-batch examples, got %d" % len(current_batch)
        )
    batch_counts = Counter(
        example["filter_fund_code"] for example in current_batch
    )
    if dict(batch_counts) != {
        code: 10 for code in CURRENT_BATCH_FUND_CODES
    }:
        raise ValueError(
            "Unexpected current-batch per-fund counts: %s"
            % dict(batch_counts)
        )

    queries = [example["query"] for example in examples]
    if len(set(queries)) != len(queries):
        raise ValueError("Duplicate queries found")

    for example in examples:
        if not example["relevant_chunk_ids"]:
            raise ValueError("%s has no relevant chunk IDs" % example["id"])
        if len(set(example["relevant_chunk_ids"])) != len(
            example["relevant_chunk_ids"]
        ):
            raise ValueError("%s has duplicate chunk IDs" % example["id"])


def write_jsonl(path, examples):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        for example in examples:
            handle.write(json.dumps(example, ensure_ascii=False) + "\n")


def main():
    args = parse_args()
    reports = get_first_report_codes(args.markdown_root)
    client = MilvusClient(uri=args.milvus_uri)
    examples = build_examples(client, args.collection)
    validate_examples(examples)
    write_jsonl(args.output, examples)

    print("Reports:")
    for report in reports:
        print("  %s" % report.relative_to(PROJECT_ROOT))
    print(
        "Wrote %d examples for %d funds to %s"
        % (len(examples), len(EXPECTED_FUND_CODES), args.output)
    )


if __name__ == "__main__":
    main()
